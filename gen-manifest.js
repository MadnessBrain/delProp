const fs = require('fs');
const path = require('path');

// Генерирует manifest.json и hosts.generated.js из шаблона и конфига хостов.
// Реальные хосты берутся из hosts.json (в .gitignore). Если его нет — используется
// hosts.example.json (заглушки), чтобы сборка не падала в чистом клоне репозитория.

function loadHosts(rootDir) {
	const realPath = path.join(rootDir, 'hosts.json');
	const examplePath = path.join(rootDir, 'hosts.example.json');

	if (fs.existsSync(realPath)) {
		return { cfg: JSON.parse(fs.readFileSync(realPath, 'utf8')), source: 'hosts.json' };
	}
	if (fs.existsSync(examplePath)) {
		console.warn('[gen-manifest] hosts.json не найден — используются заглушки из hosts.example.json');
		return { cfg: JSON.parse(fs.readFileSync(examplePath, 'utf8')), source: 'hosts.example.json' };
	}
	throw new Error('Не найден ни hosts.json, ни hosts.example.json');
}

// "https://a/*", "http://b/*" -> строка для подстановки внутри JSON-массива шаблона
function inlineList(list) {
	return list.map(item => JSON.stringify(item)).join(', ');
}

function generateManifest(rootDir, cfg) {
	const templatePath = path.join(rootDir, 'manifest.template.json');
	let text = fs.readFileSync(templatePath, 'utf8');

	text = text
		.replace('"__MAIN_MATCHES__"', inlineList(cfg.manifest.mainMatches))
		.replace('"__ARCHIVE_MATCHES__"', inlineList(cfg.manifest.archiveMatches))
		.replace('"__RESOURCE_MATCHES__"', inlineList(cfg.manifest.resourceMatches));

	// Валидируем и переписываем в аккуратном виде
	const manifest = JSON.parse(text);
	const outPath = path.join(rootDir, 'manifest.json');
	fs.writeFileSync(outPath, JSON.stringify(manifest, null, 2) + '\n');
	return outPath;
}

function generateRuntimeConfig(rootDir, cfg) {
	const runtime = cfg.runtime;
	const body =
		'// AUTO-GENERATED by gen-manifest.js — НЕ РЕДАКТИРОВАТЬ.\n' +
		'// Источник: hosts.json (в .gitignore). Файл в .gitignore и не попадает в репозиторий.\n' +
		'(function () {\n' +
		'\tvar cfg = ' + JSON.stringify(runtime, null, '\t').replace(/\n/g, '\n\t') + ';\n' +
		'\tvar g = typeof self !== "undefined" ? self\n' +
		'\t\t: (typeof window !== "undefined" ? window : globalThis);\n' +
		'\tg.DELPROP_HOSTS = cfg;\n' +
		'})();\n';

	const outPath = path.join(rootDir, 'hosts.generated.js');
	fs.writeFileSync(outPath, body);
	return outPath;
}

function generate(rootDir) {
	const { cfg, source } = loadHosts(rootDir);
	const manifestPath = generateManifest(rootDir, cfg);
	const runtimePath = generateRuntimeConfig(rootDir, cfg);
	console.log(`[gen-manifest] Источник хостов: ${source}`);
	console.log(`[gen-manifest] Сгенерирован: ${path.basename(manifestPath)}`);
	console.log(`[gen-manifest] Сгенерирован: ${path.basename(runtimePath)}`);
}

module.exports = { generate };

if (require.main === module) {
	generate(__dirname);
}
